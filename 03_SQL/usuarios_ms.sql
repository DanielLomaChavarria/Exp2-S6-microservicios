CREATE TABLE ROLES (
    ID NUMBER(10,0) GENERATED BY DEFAULT AS IDENTITY (START WITH 10 INCREMENT BY 1),
    NOMBRE VARCHAR2(255 CHAR),
    CONSTRAINT PK_ROLES PRIMARY KEY (ID)
);

CREATE TABLE DIRECCIONES (
    ID NUMBER(10,0) GENERATED BY DEFAULT AS IDENTITY (START WITH 10 INCREMENT BY 1),
    CALLE VARCHAR2(255 CHAR),
    NUMERO VARCHAR2(255 CHAR),
    COMUNA VARCHAR2(255 CHAR),
    CIUDAD VARCHAR2(255 CHAR),
    CONSTRAINT PK_DIRECCIONES PRIMARY KEY (ID)
);

CREATE TABLE USUARIOS (
    ID NUMBER(10,0) GENERATED BY DEFAULT AS IDENTITY (START WITH 10 INCREMENT BY 1),
    APELLIDO VARCHAR2(255 CHAR),
    CORREO VARCHAR2(255 CHAR),
    NOMBRE VARCHAR2(255 CHAR),
    PASSWORD VARCHAR2(255 CHAR),
    DIRECCION_ID NUMBER(10,0),
    ROL_ID NUMBER(10,0),
    CONSTRAINT PK_USUARIOS PRIMARY KEY (ID),
    CONSTRAINT UK_USUARIOS_CORREO UNIQUE (CORREO),
    CONSTRAINT UK_USUARIOS_DIRECCION UNIQUE (DIRECCION_ID),
    CONSTRAINT FK_USUARIOS_DIRECCION FOREIGN KEY (DIRECCION_ID) REFERENCES DIRECCIONES(ID),
    CONSTRAINT FK_USUARIOS_ROL FOREIGN KEY (ROL_ID) REFERENCES ROLES(ID)
);

