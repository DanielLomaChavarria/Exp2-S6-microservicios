CREATE TABLE PACIENTES (
    ID NUMBER(10,0) GENERATED BY DEFAULT AS IDENTITY (START WITH 10 INCREMENT BY 1),
    APELLIDO VARCHAR2(255 CHAR) NOT NULL,
    EDAD NUMBER(10,0) NOT NULL,
    NOMBRE VARCHAR2(255 CHAR) NOT NULL,
    RUT VARCHAR2(255 CHAR) NOT NULL,
    TELEFONO VARCHAR2(255 CHAR) NOT NULL,
    CONSTRAINT PK_PACIENTES PRIMARY KEY (ID),
    CONSTRAINT UK_PACIENTES_RUT UNIQUE (RUT),
    CONSTRAINT CK_PACIENTES_EDAD CHECK (EDAD >= 0)
);

CREATE TABLE CONSULTAS (
    ID NUMBER(10,0) GENERATED BY DEFAULT AS IDENTITY (START WITH 10 INCREMENT BY 1),
    DIAGNOSTICO VARCHAR2(255 CHAR) NOT NULL,
    FECHA VARCHAR2(255 CHAR) NOT NULL,
    MOTIVO VARCHAR2(255 CHAR) NOT NULL,
    PACIENTE_ID NUMBER(10,0) NOT NULL,
    CONSTRAINT PK_CONSULTAS PRIMARY KEY (ID),
    CONSTRAINT FK_CONSULTAS_PACIENTE
        FOREIGN KEY (PACIENTE_ID) REFERENCES PACIENTES(ID)
);

CREATE TABLE ATENCIONES (
    ID NUMBER(10,0) GENERATED BY DEFAULT AS IDENTITY (START WITH 10 INCREMENT BY 1),
    ESPECIALIDAD VARCHAR2(255 CHAR) NOT NULL,
    FECHA VARCHAR2(255 CHAR) NOT NULL,
    OBSERVACIONES VARCHAR2(255 CHAR),
    PROFESIONAL VARCHAR2(255 CHAR) NOT NULL,
    PACIENTE_ID NUMBER(10,0) NOT NULL,
    CONSTRAINT PK_ATENCIONES PRIMARY KEY (ID),
    CONSTRAINT FK_ATENCIONES_PACIENTE
        FOREIGN KEY (PACIENTE_ID) REFERENCES PACIENTES(ID)
);

